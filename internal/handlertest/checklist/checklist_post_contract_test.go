func TestHTTP_postChecklistItem_201ResponseShape(t *testing.T) {
	srv := handlertest.NewCreateServer(t)
	defer srv.Close()

	taskID := handlertest.MustCreateChecklistTask(t, srv, "chk-shape")

	res, err := http.Post(srv.URL+"/tasks/"+taskID+"/checklist/items", "application/json",
		strings.NewReader(`{"text":"first criterion"}`))
	if err != nil {
		t.Fatal(err)
	}
	defer res.Body.Close()
	raw, err := io.ReadAll(res.Body)
	if err != nil {
		t.Fatal(err)
	}
	if res.StatusCode != http.StatusCreated {
		t.Fatalf("status %d (want 201) body=%s", res.StatusCode, raw)
	}

	var top map[string]json.RawMessage
	if err := json.Unmarshal(raw, &top); err != nil {
		t.Fatalf("decode: %v body=%s", err, raw)
	}
	wantKeys := map[string]struct{}{"id": {}, "task_id": {}, "sort_order": {}, "text": {}}
	for k := range wantKeys {
		if _, ok := top[k]; !ok {
			t.Errorf("POST checklist 201 missing key %q (docs/api.md): %s", k, raw)
		}
	}
	for k := range top {
		if _, ok := wantKeys[k]; !ok {
			t.Errorf("POST checklist 201 unexpected key %q (docs/api.md): %s", k, raw)
		}
	}

	var row struct {
		ID        string `json:"id"`
		TaskID    string `json:"task_id"`
		SortOrder int    `json:"sort_order"`
		Text      string `json:"text"`
	}
	if err := json.Unmarshal(raw, &row); err != nil {
		t.Fatalf("decode envelope: %v", err)
	}
	if row.ID == "" {
		t.Error("id must not be empty")
	}
	if row.TaskID != taskID {
		t.Errorf("task_id=%q want %q", row.TaskID, taskID)
	}
	if row.SortOrder < 1 {
		t.Errorf("sort_order=%d want >=1", row.SortOrder)
	}
	if row.Text != "first criterion" {
		t.Errorf("text=%q want %q", row.Text, "first criterion")
	}
}

// TestHTTP_postChecklistItem_textRequired pins the documented 400 string for
// POST when text is missing or whitespace-only. Wording differs from PATCH's
// `text required` because the message is generated by the store, not the handler.
func TestHTTP_postChecklistItem_textRequired(t *testing.T) {
	srv := handlertest.NewCreateServer(t)
	defer srv.Close()
	taskID := handlertest.MustCreateChecklistTask(t, srv, "chk-empty")

	bodies := []struct {
		name string
		body string
	}{
		{"emptyText", `{"text":""}`},
		{"whitespaceText", `{"text":"   "}`},
	}
	for _, tc := range bodies {
		t.Run(tc.name, func(t *testing.T) {
			res, err := http.Post(srv.URL+"/tasks/"+taskID+"/checklist/items", "application/json",
				strings.NewReader(tc.body))
			if err != nil {
				t.Fatal(err)
			}
			defer res.Body.Close()
			raw, _ := io.ReadAll(res.Body)
			if res.StatusCode != http.StatusBadRequest {
				t.Fatalf("status %d (want 400) body=%s", res.StatusCode, raw)
			}
			var errBody handlertest.JSONErrorBody
			if err := json.Unmarshal(raw, &errBody); err != nil {
				t.Fatalf("decode: %v body=%s", err, raw)
			}
			if errBody.Error != "checklist text required" {
				t.Fatalf("error=%q want %q (docs/api.md)", errBody.Error, "checklist text required")
			}
		})
	}
}

// TestHTTP_postChecklistItem_rejectsRunningTask pins 409 when the task is
// in progress — criteria are locked while the agent is working.
func TestHTTP_postChecklistItem_rejectsRunningTask(t *testing.T) {
	srv, st := handlertest.NewCreateServerWithStore(t)
	defer srv.Close()
	ctx := context.Background()
	tsk, err := st.Create(ctx, taskcorestore.CreateTaskInput{
		Title: "running", Priority: taskcoredomain.PriorityMedium, Status: taskcoredomain.StatusRunning,
	}, taskcoredomain.ActorUser)
	if err != nil {
		t.Fatal(err)
	}
	res, err := http.Post(srv.URL+"/tasks/"+tsk.ID+"/checklist/items", "application/json",
		strings.NewReader(`{"text":"late criterion"}`))
	if err != nil {
		t.Fatal(err)
	}
	defer res.Body.Close()
	raw, _ := io.ReadAll(res.Body)
	if res.StatusCode != http.StatusConflict {
		t.Fatalf("status %d (want 409) body=%s", res.StatusCode, raw)
	}
	var errBody handlertest.JSONErrorBody
	if err := json.Unmarshal(raw, &errBody); err != nil {
		t.Fatalf("decode: %v body=%s", err, raw)
	}
	if !strings.Contains(errBody.Error, "cannot change criteria while task is running") {
		t.Fatalf("error=%q want substring about running", errBody.Error)
	}
}

