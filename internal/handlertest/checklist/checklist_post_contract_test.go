// TestHTTP_patchChecklistItem_doneAgentReturnsItemsView pins the documented PATCH
// happy path for `done`: 200 + full `{ "items": [...] }` with `done:true` on the
// targeted item. This complements the existing 400 coverage in
// handler_http_checklist_test.go by locking down the success-shape side.
func TestHTTP_checklist_404OnUnknownTask(t *testing.T) {
	srv := handlertest.NewCreateServer(t)
	defer srv.Close()

	const ghost = "11111111-1111-4111-8111-111111111111"
	const ghostItem = "22222222-2222-4222-8222-222222222222"

	cases := []struct {
		name string
		req  func() (*http.Response, error)
	}{
		{"POST", func() (*http.Response, error) {
			return http.Post(srv.URL+"/tasks/"+ghost+"/checklist/items", "application/json",
				strings.NewReader(`{"text":"x"}`))
		}},
		{"PATCH", func() (*http.Response, error) {
			req, _ := http.NewRequest(http.MethodPatch,
				srv.URL+"/tasks/"+ghost+"/checklist/items/"+ghostItem,
				strings.NewReader(`{"text":"x"}`))
			req.Header.Set("Content-Type", "application/json")
			return http.DefaultClient.Do(req)
		}},
		{"DELETE", func() (*http.Response, error) {
			req, _ := http.NewRequest(http.MethodDelete,
				srv.URL+"/tasks/"+ghost+"/checklist/items/"+ghostItem, nil)
			return http.DefaultClient.Do(req)
		}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			res, err := tc.req()
			if err != nil {
				t.Fatal(err)
			}
			defer res.Body.Close()
			if res.StatusCode != http.StatusNotFound {
				body, _ := io.ReadAll(res.Body)
				t.Fatalf("status %d (want 404) body=%s", res.StatusCode, body)
			}
		})
	}
}

// TestHTTP_postChecklistItem_publishesTaskUpdated colocates the per-route SSE
// positive invariant from sse_trigger_surface_test.go with the rest of this
// route's contract: a successful POST publishes exactly `task_updated:{id}`
// (and nothing else). Subscribing AFTER seed avoids draining the task_created
// frame from the seed task. Mirrors Sessions 14–17's per-route SSE pin pattern.
func TestHTTP_postChecklistItem_publishesTaskUpdated(t *testing.T) {
	srv, _, hub := handlertest.NewSSETriggerServer(t)
	defer srv.Close()
	taskID := handlertest.MustCreateChecklistTask(t, srv, "chk-sse-pos")

	ch, unsub := hub.Subscribe()
	defer unsub()

	res, err := http.Post(srv.URL+"/tasks/"+taskID+"/checklist/items", "application/json",
		strings.NewReader(`{"text":"sse positive"}`))
	if err != nil {
		t.Fatal(err)
	}
	defer res.Body.Close()
	raw, _ := io.ReadAll(res.Body)
	if res.StatusCode != http.StatusCreated {
		t.Fatalf("status %d (want 201) body=%s", res.StatusCode, raw)
	}

	events := handlertest.DrainSSE(t, ch, 1, 2*time.Second)
	got := handlertest.SummarizeSSEEvents(events)
	handlertest.MustEqualEvents(t, "POST /tasks/{id}/checklist/items", got, []string{"task_updated:" + taskID})
	handlertest.MustHaveTaskUpdatedData(t, "POST /tasks/{id}/checklist/items", events, taskID)
}

// TestHTTP_postChecklistItem_errorPathsNeverPublish pins the negative-side SSE
// invariant: 400 (text required, whitespace text, inheriting child) and 404
// (unknown task) must never publish on the SSE hub. Without this pin a future
// refactor that moved `notifyChange` above the error-write branch in
// `postChecklistItem` would silently leak ghost `task_updated` frames to clients.
func TestHTTP_postChecklistItem_errorPathsNeverPublish(t *testing.T) {
	srv, _, hub := handlertest.NewSSETriggerServer(t)
	defer srv.Close()
	parentID := handlertest.MustCreateChecklistTask(t, srv, "chk-sse-neg-parent")

	ch, unsub := hub.Subscribe()
	defer unsub()

	cases := []struct {
		name   string
		taskID string
		body   string
		want   int
	}{
		{"emptyText", parentID, `{"text":""}`, http.StatusBadRequest},
		{"whitespaceText", parentID, `{"text":"   "}`, http.StatusBadRequest},
		{"unknownTask", "11111111-1111-4111-8111-111111111111", `{"text":"x"}`, http.StatusNotFound},
	}
	for _, tc := range cases {
		res, err := http.Post(srv.URL+"/tasks/"+tc.taskID+"/checklist/items", "application/json",
			strings.NewReader(tc.body))
		if err != nil {
			t.Fatalf("%s: %v", tc.name, err)
		}
		raw, _ := io.ReadAll(res.Body)
		_ = res.Body.Close()
		if res.StatusCode != tc.want {
			t.Fatalf("%s: status %d (want %d) body=%s", tc.name, res.StatusCode, tc.want, raw)
		}
	}

	got := handlertest.SummarizeSSEEvents(handlertest.DrainSSE(t, ch, 0, 200*time.Millisecond))
	if len(got) != 0 {
		t.Fatalf("drained SSE events %v after POST checklist error round-trips; want zero (400/404 paths must never publish)", got)
	}
}

