/**
 * Prepends the checkstandards generated-file banner to vendored TipTap CLI
 * sources. Run from web/: node ./scripts/stamp-tiptap-generated.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const BANNER = "// Code generated by @tiptap/cli. DO NOT EDIT.\n";
const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(webRoot, "src");

const dirs = [
  "components/tiptap-templates",
  "components/tiptap-ui",
  "components/tiptap-ui-primitive",
  "components/tiptap-ui-utils",
  "components/tiptap-icons",
  "components/tiptap-node",
  "components/tiptap-extension",
  "contexts",
];

const extraFiles = [
  "lib/tiptap-utils.ts",
  "lib/tiptap-advanced-utils.ts",
  "lib/tiptap-collab-utils.ts",
  "hooks/use-composed-ref.ts",
  "hooks/use-isomorphic-layout-effect.ts",
  "hooks/use-on-click-outside.ts",
  "hooks/use-menu-navigation.ts",
  "hooks/use-floating-element.ts",
  "hooks/use-element-rect.ts",
  "hooks/use-unmount.ts",
  "hooks/use-throttled-callback.ts",
  "hooks/use-ui-editor-state.ts",
  "hooks/use-is-breakpoint.ts",
  "hooks/use-tiptap-editor.ts",
  "hooks/use-floating-toolbar-visibility.ts",
  "hooks/use-scrolling.ts",
  "hooks/use-window-size.ts",
  "hooks/use-cursor-visibility.ts",
];

const exts = new Set([".ts", ".tsx"]);

function walk(dir) {
  const out = [];
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) out.push(...walk(full));
    else if (exts.has(path.extname(ent.name))) out.push(full);
  }
  return out;
}

const files = dirs.flatMap((rel) => walk(path.join(src, rel)));
for (const rel of extraFiles) files.push(path.join(src, rel));

let stamped = 0;
for (const file of files) {
  if (!fs.existsSync(file)) continue;
  const text = fs.readFileSync(file, "utf8");
  if (text.startsWith("// Code generated")) continue;
  fs.writeFileSync(file, BANNER + text);
  stamped += 1;
}

console.log(`stamped ${stamped} of ${files.length} files`);
